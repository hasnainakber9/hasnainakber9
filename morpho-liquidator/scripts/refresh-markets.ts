// Regenerates config/markets.base.json: the explicit market whitelist.
//
// The whitelist is a safety boundary, so it is a reviewed file in git, not a
// runtime lookup. Run this, read the diff, commit it.
//
//   pnpm refresh-markets [--min-borrow-usd 100000]
//
// Selection: markets the Morpho API marks as listed on Base, with at least
// --min-borrow-usd borrowed and no warnings attached.

import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const API = 'https://api.morpho.org/graphql'
const arg = (name: string, fallback: string) => {
  const i = process.argv.indexOf(name)
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1]! : fallback
}
const minBorrowUsd = Number(arg('--min-borrow-usd', '100000'))

const query = `{
  markets(first: 500, orderBy: BorrowAssetsUsd, orderDirection: Desc, where: { chainId_in: [8453], listed: true }) {
    items {
      marketId lltv
      loanAsset { symbol }
      collateralAsset { symbol }
      state { borrowAssetsUsd }
      warnings { type level }
    }
  }
}`

const response = await fetch(API, {
  method: 'POST',
  headers: { 'content-type': 'application/json' },
  body: JSON.stringify({ query }),
  signal: AbortSignal.timeout(30_000),
})
if (!response.ok) throw new Error(`Morpho API HTTP ${response.status}`)
const body = (await response.json()) as {
  errors?: { message: string }[]
  data?: { markets: { items: any[] } }
}
if (body.errors?.length) throw new Error(`Morpho API: ${body.errors[0]!.message}`)

const markets = body
  .data!.markets.items.filter((m) => m.collateralAsset && (m.state?.borrowAssetsUsd ?? 0) >= minBorrowUsd)
  .filter((m) => (m.warnings ?? []).length === 0)
  .map((m) => ({
    id: String(m.marketId).toLowerCase(),
    label: `${m.collateralAsset.symbol}/${m.loanAsset.symbol} ${(Number(m.lltv) / 1e16).toFixed(1)}%`,
  }))

if (markets.length === 0) throw new Error('no market matched; refusing to write an empty whitelist')

const out = {
  chainId: 8453,
  generatedAt: new Date().toISOString(),
  note: `Listed Base markets with >= $${minBorrowUsd} borrowed and no API warnings. Generated by scripts/refresh-markets.ts; review the diff before committing.`,
  markets,
}
const path = resolve(process.cwd(), 'config/markets.base.json')
writeFileSync(path, JSON.stringify(out, null, 2) + '\n')
console.log(`wrote ${markets.length} markets to ${path}`)
